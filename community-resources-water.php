            <h3>Pierce County &lsquo;s Environmental Education Team            </h3>
            <ul class="bullet-size-fix">
              <li><strong>Website</strong><em>: </em><a href="https://www.piercecountywa.gov/1555/Environmental-Education">Environmental  Education | Pierce County, WA - Official Website</a></li>
              <li><strong>Description</strong><em>: </em>This team provides  free/low-cost classes around environmental topics in schools and supports youth programming and networking opportunities focused on climate  justice and other topics. They also have specific initiative work focused on  topics like food waste, rain gardens, and more. Their <a href="https://www.piercecountywa.gov/1586/Earth-Matters-Newsletter">Earth  Matters Newsletter</a> is also a great resource to learn new tools and tips for  the waste reduction and recycling.</li>
        </ul>
        <h3>Storming the Sound Conference</h3>
            <ul class="bullet-size-fix">
              <li><strong>Website</strong>: <a href="https://www.pacname.org/regional-chapters/washington/storming-the-sound/">Storming  the Sound - Northwest Aquatic and Marine Educators</a></li>
              <li><strong>Description</strong>: &ldquo;Storming  the Sound is a conference for environmental educators in the north Puget Sound  region, including the counties of Whatcom, Skagit, Snohomish, Island, Jefferson  and San Juan. Every January, teachers, environmental organizations and students  gather to share their interest and expertise in environmental education  (source: website home page). This event tackles climate justice, Puget Sound  issues, and more.            </li>
            </ul>
