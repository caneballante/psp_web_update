              <li><strong>Description</strong><em>:</em> This program on the  YMCA works with middle and high-school-aged youth in the greater Seattle area  to provide education, hands-on experience, and leadership training. Climate  justice and water quality is one of many topics that they focus on.</li>
              <li><strong>Contact</strong><em>: </em>Chelsey Wheeler,  Director, <a href="mailto:cwheeler@seattleymca.org">cwheeler@seattleymca.org</a></li>
