            </ul>
            <h3>Dirt Corps</h3>
        <ul class="bullet-size-fix">
              <li><strong>Website</strong><em>:</em> <a href="https://www.thedirtcorps.com/">The Dirt Corps - Dirt Corps</a></li>
              <li><strong>Description</strong><em>:</em> This organization  operates in South Seattle and is focused on providing paid on-the-job training  focused on topics including Green Infrastructure, Ecological Restoration and  Urban Forestry. They also host volunteer events.</li>
              <li><strong>Contact</strong><em>: </em>Andrew Schiffer,  Principal &amp; Director of Community Partnerships, <a href="mailto:andrew@thedirtcorps.com">andrew@thedirtcorps.com</a></li>
