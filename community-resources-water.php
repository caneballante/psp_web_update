                </li>
              </ul>
            </ul>
            <h3>King County Parks Youth Conservation Corps</h3>
        <ul class="bullet-size-fix">
              <li><strong>Website</strong><em>:</em> <a href="https://kcpyouthcorps.org/">King County Parks Youth Conservation Corps</a></li>
              <li><strong>Description</strong><em>:</em> Offers  a paid summer internship program that teaches youth about conservation. Their  projects mostly focus on restoration.</li>
