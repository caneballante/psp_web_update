			<p>The Puget Sound Partnership Boards welcome public participation in their meetings. The meeting dates and locations are posted on our <a href="https://psp.wa.gov/board_meetings.php">Boards Meeting Schedule page</a> and each meeting is streamed live and recorded on <a href="https://tvw.org/" target="new">TVW.</a> A common way for public participation on the boards is by making a public comment. Below, you can find more information to help you know what to expect during public comment on the boards</p>
	    <h2>Ways to Make Public Comments</h2>
		      <p>All comments provided become part of the Boards' public records, such as their briefing materials (written comments) or in the meeting summary (spoken comments). Members of the public can submit a written comment to any of the Puget Sound Partnership Boards. For the Leadership Council and Ecosystem Coordination Board, members of the public can also share a comment verbally in a Board meeting. There are certain topics where there may be a public comment period offered by the Puget Sound Partnership outside of the Board meeting, which is indicated in the briefing materials for that topic. For example, the <a href="https://psp.wa.gov/2026AAupdate.php" target="new">Action Agenda</a> and <a href="https://psp.wa.gov/PSAR.php" target="new">Puget Sound Acquisition and Restoration</a> program have public comment periods.</p>
		      <h2>Written comments</h2>
		      <p>To submit written comments to the Boards, please email Amber.Raney@psp.wa.gov by noon 
		      the day before the meeting. Staff will then share the comment in the briefing packet.</p>
        <h2>Spoken Comments</h2>
	        <p>The Leadership Council and Ecosystem Coordination Board include 15 minutes on each agenda to hear public comments. To provide a spoken comment, fill out and submit a comment card at the meeting sign in table at least 15 minutes before the scheduled public comment topic on the agenda. To provide a spoken comment in a virtual meeting, please email <a href src="mailto:Amber.Raney@psp.wa.gov" target="new">Amber.Raney@psp.wa.gov</a> by noon the day before the meeting. Staff will then share the directions and link to join the meeting virtually.</p>
		      <p>The Board Chair will call on your name and invite you to sit at the presenter’s table if the meeting is in person. For a virtual meeting, the Board Chair will invite you to unmute and share your comment. Speak clearly and start by sharing your name for the record. Please keep your comments to 3 minutes to allow time for others to provide comments.</p>
		      <h2>Shared Principles of Partner Respect and Engagement</h2>
        <p>We promote a safe and productive working environment sponsored by our agency, councils, and boards. Our partners and Boards follow the <a href="https://psp.wa.gov/partner-engagement.php" target="new"> Shared Principles of Partner Respect and Engagement,</a> and we expect any public comments to follow these principles.</p>
		      <h2>Tips on Making Effective Comments</h2>
		      <ul class="bullet-size-fix">
		        <li > Start by introducing yourself and whether you are representing yourself or a group or
	            organization.</li>
		        <li>Address your comments to the board members, not to the audience.</li>
		        <li>Speak loud enough for everyone in the room and online to hear your voice.</li>
		        <li>Make your remarks brief and clear, limiting them to three minutes.</li>
		        <li>Comment only on issues relevant to the role of the Board, Puget Sound Partnership or
	            Puget Sound recovery.</li>
		        <li>Explain how your comment connects to the purpose and role of the Board.</li>
		        <li>Avoid being too technical. Avoid using acronyms to help make sure that everyone 
	            understands the message you are delivering.</li>
		        <li>Do not repeat remarks made by others. If you know others will be offering similar comments, try to coordinate to avoid duplication.</li>
		        <li> State opinions and preferences, ask questions, and propose alternative solutions to issues. Where possible, include data to support your opinion. We value subjective and objective data, which can take many forms.</li>
		        <li> Be prepared to answer questions and comments from board members.</li>
		        <li> Use facts and objective evidence.</li>
		        <li> Consider providing your contact information for board members to follow up or ask additional questions.</li>
        </ul>
		      <p><strong>For additional questions</strong> about how to provide public comments to the Partnership’s Boards,
