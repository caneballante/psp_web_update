<h2>Approach and timeline </h2>
		  <img class="floatright" src="images/management-cycle-1.png" alt="An image of the simplified adaptive management cycle. Four arrows make up a circle to show that each part of the cycle interacts with the others. Each arrow says Evaluate and Learn, Adjust, Plan, and Do."/>
<p>The   2026-2030 Action Agenda update process follows an adaptive management approach.  Over the course of 2025, the Partnership will work with recovery partners to <strong>evaluate  and learn</strong> from successes and challenges to implementing the 2022-2026  Action Agenda (<strong>plan</strong>) and <strong>adjust</strong> the 2026-2030 Action Agenda as  needed. The 2026-2030 Action Agenda is scheduled to be approved in summer 2026.<strong></strong></p>
