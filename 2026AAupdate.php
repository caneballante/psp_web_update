		<h2 class="margin-0-top">We are updating the Puget Sound Action Agenda </h2>
		<p>The Action Agenda is our community&rsquo;s  shared plan for advancing Puget Sound recovery. The 2026-2030 Action Agenda  update will advance progress towards recovery of the Puget Sound&rsquo;s ecosystem and human wellbeing <a href="https://vitalsigns.pugetsoundinfo.wa.gov/" target="new">Vital Signs</a> by building on  the foundation of the<a href="https://www.psp.wa.gov/2022AAupdate.php" target="new">2022-2026  Action Agenda</a>.</p>
		<p>The 2026-2030 Action Agenda will describe approaches that include   ecosystem health, human wellbeing, climate change, and  environmental justice. The plan will have Strategies and Actions that guide  implementation, including commitments from Puget Sound recovery partners. It  will also include more indicators and targets designed to help us assess the  effectiveness of our collective efforts and hold us all accountable to making  meaningful progress. </p>
        <p>The goals of the update are to: </p>
        <ul>
          <li>Strengthen implementation, accountability,  alignment and tracking of the Action Agenda.   </li>
          <li>Elevate and further integrate human  wellbeing, climate change, and environmental justice.</li>
          <li>Elevate and honor Tribal sovereignty and treaty  rights.</li>
          <li> Expand participation and  meaningful engagement of diverse audiences, including vulnerable  populations (VP) and overburdened communities (OBC)</li>
          <li>Update the online Action Agenda to improve  accessibility and usability. </li>
        </ul>
