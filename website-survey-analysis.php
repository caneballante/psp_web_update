	<section class="container survey-section" aria-labelledby="watchouts-title">
		<div class="survey-section-heading">
			<p class="survey-kicker">Guardrails</p>
			<h2 id="watchouts-title">What Not to Overbuild</h2>
		</div>
		<div class="survey-guardrail-grid">
			<article>
				<h3>Do not merge every website immediately.</h3>
				<p>Only 15 respondents preferred everything in one place, while 13 gave nuanced comments. Improve the experience across sites first, then decide what truly belongs together.</p>
			</article>
			<article>
				<h3>Do not add interactivity without a job.</h3>
				<p>Interactive data and visuals are popular, but comments also warned against adding clutter. Prioritize visualizations that help visitors answer a question or understand progress.</p>
			</article>
			<article>
				<h3>Do not treat visual refresh as the whole fix.</h3>
				<p>Respondents want the site to feel more modern, but the deeper issue is information architecture, content ownership, and findability.</p>
			</article>
		</div>
	</section>

