            <h2>EPA&rsquo;s Technical Assistance offerings:</h2>
        <ul class="bullet-size-fix">
              <li>Thriving  Communities Technical Assistance Centers </li>
              <ul>
                <li><strong>Who</strong>: Communities with environmental justice  considerations.</li>
                <li><strong>What</strong>: Customized assistance to work toward communities'  goals - finding grants, reviewing applications and giving advice, planning  documentation, feasibility studies, or other services.</li>
                <li><strong>How much</strong>: Centers remain open for at least five years to  deliver free technical assistance.</li>
                <li>This program  stems from the previous Federal Justice40 Initiative, which seeks to address  inequities in federal funding to environmental justice communities. The <a href="https://www.epa.gov/environmentaljustice/thriving-communities-network-tcn?utm_medium=email&utm_source=govdelivery">Thriving Communities Network</a> is a federal interagency effort to coordinate  place-based technical assistance and capacity-building resources for urban,  rural, and Tribal communities experiencing a history of economic distress and  systemic disinvestment. There are 16 Thriving Communities Technical Assistance  Centers across the nation, both Northwest Environmental Justice Center and the  University of Washington Center for Environmental Health Equity serve all of  EPA Region 10 (Alaska, Idaho, Oregon, and Washington).</li>
              </ul>
              <li><a href="https://www.epa.gov/water-infrastructure/real-water-technical-assistance-realwaterta">Real  Water Technical Assistance</a> (RealWaterTA) focuses on public health and compliance  with the Safe Drinking Water Act and Clean Water Act. It also prioritizes  accountability for technical assistance providers and real-world results.  Technical assistance will benefit Americans across the country, especially in  rural areas where small systems face challenges operating and maintaining vital  water infrastructure.&nbsp;</li>
              <ul>
                <li>Part of RealWaterTA, <a href="https://www.epa.gov/water-infrastructure/waterta-engineering-support">Engineering Support Services</a> can provide communities with the engineering  expertise needed to apply for EPA funding for drinking water, wastewater, and  stormwater infrastructure projects. This is a no-cost, supplemental RealWaterTA  service to help communities identify needs, conduct preliminary project  planning analyses, and produce the engineering documents as part of EPA&rsquo;s  administration of the Clean Water and Drinking Water State Revolving Funds. </li>
              </ul>
            </ul>
            <ul class="bullet-size-fix">
              <li><a href="https://interagency-bil-fish-passage-project-1-fws.hub.arcgis.com/">Fish Passage Portal</a> – &ldquo;one-stop-shop&rdquo; for information,  funding, and resources to improve fish passage and aquatic connectivity projects.            </li>
            </ul>
            <ul class="bullet-size-fix">
              <li>NOAA Fisheries  provides scientific and technical assistance to help plan, design, and  implement effective and efficient habitat restoration projects in coastal and  marine habitats across the country through their <a href="https://www.fisheries.noaa.gov/national/habitat-conservation/providing-technical-support-habitat-restoration-efforts">Providing Technical Support for Habitat Restoration  Efforts</a> program. </li>
        </ul>
            <h2>Transportation Focused  Resources</h2>
        <ul>
          <ul class="bullet-size-fix">
                <li>To help navigate  transportation grant programs and expedite applications, the B<a href="https://billaunchpad.com/">IL Launchpad</a> provides customized information on available funding,  interactive technical support, data on successful awards, and essential  resources. </li>
                <li>The <a href="https://www.transportation.gov/grants">DOT  Navigator</a> is a new resource to help  communities understand the best ways to apply for grants, and to plan for and  deliver transformative infrastructure projects and services. </li>
                <li>The <a href="https://www.transportation.gov/grants/dashboard">DOT Discretionary Grants Dashboard</a> provides communities with an overview of discretionary grant  opportunities that can help meet their transportation infrastructure needs.  Designed with all communities in mind, the Dashboard identifies grant programs  that rural and Tribal set-asides or match waivers available. </li>
            <li>The Maritime  Administration works side by side with the nation&rsquo;s shipbuilders and  port/waterway operators to ensure a robust and profitable maritime industry.  DOT offers <a href="https://www.maritime.dot.gov/grants-finances">a number of funding opportunities</a>, grants (BUILD and INFRA) and loans (TIFIA and RRIF)  designed to:</li>
                <ul>
                  <li>Advance ship construction, repair, and training at  shipyards across the U.S.,</li>
                  <li>Develop and expand our nation&rsquo;s port infrastructure  and waterways, and Promote the growth and modernization of the U.S.  maritime industry.            </li>
