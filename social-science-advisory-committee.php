		  <h2>SSAC Key Products and Publications</h2>
        <p><strong><a href="https://www.tandfonline.com/action/showAxaArticles?journalCode=ucmg20" target=new>2026 Special  Issue for Coastal Management (Volume 54, Issue 05)</a></strong>            
            <p> 
              This special issue of <em>Coastal Management</em>, which was guest-edited by the  SSAC,highlights the innovative approaches that have made the Puget  Sound a global leader in applied environmental social sciences for more than a  decade. With a mix of case studies, reviews, and policy pieces, it reflects on  the essential role that social sciences play in advancing coastal management  planning, monitoring, project design, and implementation in the Puget Sound  region.
        <p>The collection of articles celebrates the 12th anniversary  of a previous <em><a href="https://www.tandfonline.com/toc/ucmg20/42/4">Coastal Management special issue (42; 4)</a></em> that focused on Puget Sound social science. It also highlights progress in  applying the social sciences to ecosystem recovery and shares lessons for other  regions. <br>
Included articles:             
        <ul class="bullet-size-fix">
              <li>Present social scientific studies with applied  implications for Puget Sound ecosystem recovery. </li>
              <li>Report on and critically analyze approaches to  institutionalizing and integrating social sciences into natural resource  management decision-making processes, such as the Social Sciences Advisory  Committee (SSAC). </li>
              <li>Highlight the critical role of the social  sciences in addressing environmental injustices and incorporating diverse ways  of knowing in coastal ecosystem recovery in the Puget Sound region and beyond. </li>
              <li>Explore some of the crucial gaps, challenges,  and areas of opportunity facing social science integration in recovery. </li>
              <li>Share researchers&rsquo; and practitioners&rsquo;  experience-driven visions to expand the scope and influence of the social  sciences in regional ecosystem recovery. </li>
            </ul>
            <p>Special Issue Contents:</p>
            <ul class="bullet-size-fix" type="disc">
              <li>Breslow, S.J.;       Hollender, R.; Trimbach, D.J.; Koontz, T.M;  Chang M.H., Anderson, R.M.; Rozance,       M.A.; Watson, J.; Clifton, K.; Flight, M.; Fonner, R.; Lewis-Smith, C.;       Morgan, A.; Naar, N. (08 Jun 2026): Daylighting the Environmental Social       Sciences for Coastal Management: Introduction to the Special Issue,       Coastal Management.</li>
