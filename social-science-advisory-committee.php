		<h2>Objectives</h2>
			<p>The SSAC:<strong><br>
			</strong></p>
            <ul class="bullet-size-fix">
              <li>Promotes best available social science to  support Puget Sound and Salish Sea recovery goals, strategies, and products.</li>
              <li>Encourages ecosystem recovery strategies that reflect  the needs and aspirations of the people and communities of the Puget Sound  region. </li>
              <li>Supports collaboration across social science  disciplines and between the natural and social sciences.</li>
              <li>Provides input on our or PSI calls for new  research.</li>
              <li>Contributes social science priorities to our  Science Work Plan via the 2024 Social Sciences for the Puget Sound (PS4)  report.</li>
              <li>Provides a forum to share and critique applied  regional social science research projects and papers.</li>
              <li>Identifies and encourage opportunities for  social science contributions to our Science Panel and other boards.</li>
              <li>Supports strong social science contributions in  the Salish Sea Ecosystem Conference. 
