            <p><strong>Featured Publication: </strong> <strong><a href="https://www.tandfonline.com/doi/full/10.1080/08920753.2026.2682001">Daylighting  the Environmental Social Sciences for Coastal Management: Introduction to the  Special Issue</a></strong><br>
              Social sciences make important contributions to coastal and  ocean management. For example, it can explain the social drivers of ecosystem  degradation, identify factors that influence public support for and  participation in restoration and stewardship, and theorize effective  environmental governance. <br>
              This special issue follows the <em>Coastal Management </em>2014  special issue on the role of social sciences in Puget Sound recovery. It  showcases the range of social science research now supporting Puget Sound  ecosystem recovery. <br>
              The introduction to the special issue offers an overview of  environmental social sciences (ESS) and describes the social conditions making  Puget Sound an important area for ESS research. Four featured articles  highlight specific applications to Puget Sound management and unique social  science strengths. <br>
              The introduction also discusses misconceptions and systemic barriers  that can limit the full potential of ESS to contribute alongside the  biophysical sciences in addressing environmental challenges. To &ldquo;daylight&rdquo; a  stream means to remove obstructions and restore its ecological function: with  this issue we strive to daylight the value of social sciences to coastal and  ocean management. The issue concludes with lessons for growing a robust ESS  community of practice here and elsewhere.<br>
  <strong><a href="https://pspwa.box.com/s/9c5272fegxy6fv8piybqlpvblwjcosip">2024 Puget  Sound Social Science Research Agenda (PS3)</a></strong><br>
              The Puget Sound Social Science Research Agenda (PS3) identifies priority social  science needs for Puget Sound ecosystem recovery.<br>
              PS3 updates the 2019 Social Science for the Salish Sea  report (S4) and promotes the production and use of social sciences in Puget  Sound recovery decisions. The agenda is intended for planners, researchers, and  funders, and supports improved social science integration and decision-making  across Puget Sound recovery projects.<br>
  <strong>2019 </strong><a href="https://pspwa.box.com/shared/static/iak8x19qh0qhem1qhsvqhmgcnmdg9m2g.pdf" target="new"><strong>Social Science for the Salish Sea (S4)</strong></a><br>
              The Social Science for the Salish Sea (S4) project began in response to our  need for stronger social science to inform regional ecosystem recovery  strategies.</p>
            <p>Through a partnership with the University of  Washington&rsquo;s EarthLab, the  SSAC  brought  together researchers and practitioners from both sides of the U.S. and Canada  to develop an action-oriented social science research agenda. The agenda  supports practical ecosystem recovery across the Salish Sea, including British  Columbia&rsquo;s Georgia Basin and Washington State&rsquo;s Puget Sound.</p>
