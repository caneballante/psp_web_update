			<p>The Puget Sound Social Sciences Advisory Committee (SSAC)  was established in 2010 by our <a href="https://www.psp.wa.gov/SP_about.php" target="new">Science Panel</a>. It brings together social scientists and recovery  specialists from multiple disciplines to advise us on social sciences, salmon  and ecosystem recovery, equity, environmental justice. and other recovery  goals.</p>
			<p>Committee members include social scientists from  academic, government, and non-profit institutions across the Puget Sound and  Salish Sea region and beyond.</p>
		<div>
  <div> </div>
		</div>
			<h2 class="margin-0-top">VISION</h2>
			<p>The SSAC integrates social science research and human dimensions into our planning, decision-making, and adaptive management. This helps create more complete and effective recovery strategies that strengthen the resilience of Puget Sound ecosystems and communities. </p>
			<h2>PURPOSE</h2>
			<p>The  SSAC meets monthly to: <br>
        </p>
            <ul class="bullet-size-fix">
              <li>Build regional capacity in the social sciences</li>
              <li>Discuss advancements in social science research  and monitoring </li>
              <li>Review our materials</li>
              <li>Guide priority social science for the region </li>
              <li>Foster shared learning and collaboration among  members&rsquo; networks. </li>
              <li>The SSAC also helps inform the work of the Puget  Sound Institute (PSI) in support of shared recovery efforts.
                <div>
                  <div></div>
                </div>
              </li>
            </ul>
		<h2>SSAC Objectives<strong><br>
		</strong></h2>
            <ul class="bullet-size-fix">
              <li>Promote best available social science to  support Puget Sound and Salish Sea recovery goals, strategies, and products.</li>
              <li>Encourage ecosystem recovery strategies that reflect  the needs and aspirations of the people and communities of the Puget Sound  region. </li>
              <li>Support collaboration across social science  disciplines and between the natural and social sciences.</li>
              <li>Provide input on our or PSI calls for new  research.</li>
              <li>Contribute social science priorities to our  Science Work Plan via the 2024 Social Sciences for the Puget Sound (PS4)  report.</li>
              <li>Provide a forum to share and critique applied  regional social science research projects and papers.</li>
              <li>Identify and encourage opportunities for  social science contributions to our Science Panel and other boards.</li>
              <li>Support strong social science contributions in  the Salish Sea Ecosystem Conference. 
       		  </li>
            </ul>
