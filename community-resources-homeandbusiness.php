        <h2 id="section1" class="resource-section-anchor">SEATTLE</h2>
        <h3>RainCity Partnerships</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website:</strong> <a href="https://raincity.partners/">RainCity Partnerships</a></li>
          <li><strong>Description</strong>: The RainCity Partnerships  project supports private landowners installing Green Stormwater Infrastructure  (GSI) on their property. It mainly aims to cooperate with BIPOC and immigrant  and refugee communities. RainCity Partnerships supports the design and  construction of GSI at no cost and covers the first three years of maintenance  fees. The partnership between Seattle Public Utilities (SPU) and CIS (a private  company) takes charge of RainCity Partnerships under the guidance of SPU&rsquo;s  50-year plan, Shape Our Water.</li>
        </ul>
        <h4>RainWise Program</h4>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://700milliongallons.org/rainwise/">RainWise</a></li>
          <li><strong>Description</strong>: Prevents flooding on   properties, adds nice looking garden space, and collects rain water to use for  watering plants (while saving money on water bills). RainWise also gives rebates,  cisterns, and rain gardens to eligible properties in Seattle. Learn more <a href="https://700milliongallons.org/rainwise/">here</a>. </li>
        </ul>
        <h4>Trees for Neighborhoods</h4>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.seattle.gov/trees/">Trees for Seattle - Trees | seattle.gov</a></li>
          <li><strong>Description</strong>: Receive a free tree to plant  in Seattle. Learn more <a href="https://www.seattle.gov/trees/trees-for-neighborhoods">here</a>.</li>
        </ul>
        <h4>Seattle Public Utility Resources for service related to water quality</h4>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.seattle.gov/utilities/neighborhood-projects">Neighborhood  Projects - Utilities | seattle.gov</a></li>
          <li><strong>Description</strong>: Find information about  planned water outages, projects planned in your neighborhood, how sewer repair  might impact your neighborhood, and more. </li>
        </ul>
        <h4>Seattle Public Utility Green Business Assistance Program</h4>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.seattle.gov/utilities/protecting-our-environment/sustainability-tips/green-business-program">Green  Business Program - Utilities | seattle.gov</a></li>
          <li><strong>Description</strong>: If you are a business owner,  the City of Seattle has free technical assistance and resources to help you  conserve waste, prevent expensive backups in pipes, save on waste bills, and  more. </li>
        </ul>
        <h4>Seattle Public Utility Resources for discounts and incentives</h4>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.seattle.gov/utilities/your-services/discounts-and-incentives">Discounts  &amp; Incentives - Utilities | seattle.gov</a></li>
          <li><strong>Description</strong>: Utility Discount Program-  eligible households can get a discount on their bills for lighting, water,  sewer, garbage, drainage, and yard waste. Find more information and apply <a href="https://www.seattle.gov/utilities/your-services/discounts-and-incentives/utility-discount-program#En_x162078">here</a>.  If you&rsquo;re in the discount program, you can also get two free special item pickups  (to safely dispose of things like TVs, foam blocks, or batteries) and free  transfer station passes.</li>
          <li><strong>Stormwater facility credit</strong>: Save money on  the drainage fee that the City of Seattle charges if you have a qualifying  stormwater system on your property. Learn more <a href="https://www.seattle.gov/utilities/your-services/discounts-and-incentives/stormwater-facility-credit">here</a>.</li>
          <li>Low-income customer may get a $100 toilet replacement rebate, $100  sprinkler timer rebate, or  a free water saving toilet. Learn more <a href="https://www.seattle.gov/utilities/protecting-our-environment/sustainability-tips/conserve-water/for-residents">here</a>.  This page also has information about free gardening classes and how to check  for and fix leaks. </li>
        </ul>
