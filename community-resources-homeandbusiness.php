        <h2 id="section2" class="resource-section-anchor">TACOMA</h2>
        <h3>Make a Splash Grant Program</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.cityoftacoma.org/government/city_departments/environmentalservices/surface_water/make_a_splash_stormwater_project_funding#:~:text=Apply%20for%20a%20Make%20a%20Splash%20grant%20through,and%20restore%20our%20lakes%2C%20streams%20and%20Puget%20Sound.">Make  a Splash Stormwater Project Funding - City of Tacoma</a></li>
          <li><strong>Description</strong>: The City of Tacoma&rsquo;s  Stormwater Management program awards projects with a strong stormwater message  and educational programs up to $4,000. The projects must be within Tacoma  city limits and not about water conservation or clean drinking water. It can be  classroom projects, community projects, and business projects. </li>
          <li><strong>Contact</strong>: Have questions?  Contact Kirsti Lipphardt, the Make a Splash Program manager, or Nathaniel Wood  at <a href="mailto:NWood@cityoftacoma.org">NWood@cityoftacoma.org</a> or call (253) 719-3771. </li>
        </ul>
        <h3>Tacoma Tree Foundation</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://tacomatreefoundation.org/">Tacoma Tree Foundation</a></li>
          <li><strong>Description</strong>: Receive a free tree to plant and  planting assistant in Tacoma. Learn more <a href="https://tacomatreefoundation.org/programs">here</a>. Tacoma Tree  Foundation has a platform to share tree related programs <a href="https://tacomatreefoundation.org/treestacoma">here</a>.</li>
        </ul>
        <h3>Tacoma Public Utilities water rebates and resources</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.mytpu.org/ways-to-save/business-rebates/#pattern_10">Business  Rebates - Tacoma Public Utilities</a></li>
          <li><strong>Description</strong>: Businesses (including those who  rent their business space) can receive rebates for a variety of water-saving  equipment, such as dishwashers, steam cookers, and smart irrigation. They can  get a free water saving assessment. Learn more<a href="https://www.mytpu.org/ways-to-save/business-rebates/commercial-water-incentives/">here</a>. </li>
          <ul>
            <li>Homeowners can access the <a href="https://www.mytpu.org/ways-to-save/business-rebates/smart-irrigation-rebate-for-businesses/#pattern_10">smart  irrigation rebate,</a> <a href="https://www.mytpu.org/payment-billing/payment-information/payment-assistance/water-grants-and-loans/">financial  help replacing a leaking/aged water line</a>, and can get a <a href="https://www.mytpu.org/ways-to-save/save-water-lower-bill/">free water  saving kit</a> as well as tips on how to find and fix leaks to lower water  bills.</li>
            <li>Information about water supply and bottle  filling locations can be found<a href="https://www.mytpu.org/about-tpu/services/water/water-source/#pattern_6">here</a>. </li>
          </ul>
          <li><a href="https://www.mytpu.org/payment-billing/payment-information/payment-assistance/#pattern_1">Payment  Assistance - Tacoma Public Utilities</a></li>
          <ul class="bullet-size-fix">
            <li>Qualified homeowners can receive payment  assistance with utility bills. Available in Spanish. </li>
          </ul>
        </ul>
