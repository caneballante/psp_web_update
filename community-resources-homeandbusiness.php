        <h2 id="section1" class="resource-section-anchor">SEATTLE</h2>
        <p><strong>RainCity Partnerships</strong></p>
        <ul class="bullet-size-fix">
          <li>Website<strong>:</strong> <a href="https://raincity.partners/">RainCity Partnerships</a></li>
          <li>Description: The RainCity Partnerships  project supports private landowners installing Green Stormwater Infrastructure  (GSI) on their property. It mainly aims to cooperate with BIPOC and immigrant  and refugee communities. RainCity Partnerships supports the design and  construction of GSI at no cost and covers the first three years of maintenance  fees. The partnership between Seattle Public Utilities (SPU) and CIS (a private  company) takes charge of RainCity Partnerships under the guidance of SPU&rsquo;s  50-year plan, Shape Our Water.</li>
        </ul>
        <h4>RainWise Program</h4>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://SeattleRainWise.org">RainWise</a></li>
          <li>Description: RainWise is a partnership program of King County Wastewater Treatment Division (WTD) and Seattle Public Utilities (SPU) that provides rebates for rain gardens and cisterns built on eligible properties within Seattle. RainWise keeps polluted water out of Seattle waterways by reducing combined sewer overflows. To be eligible for the RainWise rebate your property must be in a RainWise eligible area and be connected to the combined sewer system.<a href="https://SeattleRainWise.org"> Find more information and check your eligibility.</a>. </li>
        </ul>
        <h4>Trees for Neighborhoods</h4>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.seattle.gov/trees/">Trees for Seattle - Trees | seattle.gov</a></li>
          <li>Description: Receive a free tree to plant  in Seattle. Learn more <a href="https://www.seattle.gov/trees/trees-for-neighborhoods">here</a>.</li>
        </ul>
        <h4>Seattle Public Utility Resources for service related to water quality</h4>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.seattle.gov/utilities/neighborhood-projects">Neighborhood  Projects - Utilities | seattle.gov</a></li>
          <li>Description: Find information about  planned water outages, projects planned in your neighborhood, how sewer repair  might impact your neighborhood, and more. </li>
        </ul>
        <h4>Seattle Public Utility Green Business Assistance Program</h4>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.seattle.gov/utilities/protecting-our-environment/sustainability-tips/green-business-program">Green  Business Program - Utilities | seattle.gov</a></li>
          <li>Description: If you are a business owner,  the City of Seattle has free technical assistance and resources to help you  conserve water, prevent expensive backups in pipes, save on  bills, and  more. </li>
        </ul>
        <h4>Seattle Public Utility Resources for discounts and incentives</h4>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.seattle.gov/utilities/your-services/discounts-and-incentives">Discounts  &amp; Incentives - Utilities | seattle.gov</a></li>
          <li>Description: Through the Utility Discount Program, eligible households can get a discount on their bills for lighting, water, sewer, garbage, drainage, and yard waste. Find more information and apply <a href="https://www.seattle.gov/utilities/your-services/discounts-and-incentives/utility-discount-program#En_x162078">here</a>.  If you&rsquo;re in the discount program, you can also get two free special item pickups  (to safely dispose of things like TVs, foam blocks, or batteries) and free  transfer station passes.</li>
          <li>Description: Stormwater facility credit: Through the Stormwater Facility Credit Program, property owners can save money on the drainage fee that the City of Seattle charges if they have a qualifying stormwater system on their property. <a href="https://www.seattle.gov/utilities/your-services/discounts-and-incentives/stormwater-facility-credit">Learn more</a>.</li>
          <li>Description: Through the Saving Water Partnership, low-income customers may get a $100 toilet replacement rebate, $100 sprinkler timer rebate, or a free water saving toilet. This page also has information about free gardening classes and how to check  for and fix leaks.<a href="https://www.seattle.gov/utilities/protecting-our-environment/sustainability-tips/conserve-water/for-residents">Learn more</a>. </li>
        </ul>
