        <h3>Neighborhood Stormwater Funding</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://pugetsoundestuary.wa.gov/2025/04/07/neighborhood-stormwater-rfp-opening-soon/?utm_medium=email&utm_source=govdelivery">Neighborhood  Stormwater RFP Opening Soon - Strategic Initiatives of the Puget Sound National  Estuary Program</a></li>
          <li><strong>Description</strong>: Starting May 7, 2026(ending July 9),  you can apply for funding for projects that improve the health of water that  flows through hard surfaces and picks up pollutants. Projects must include  some aspect of education (example: teaching real estate agents or HOAs or building  owners about best practices) and technical assistance (example: tree planting  events, providing green stormwater infrastructure training). Use <a href="https://forms.office.com/pages/responsepage.aspx?id=F-LQEU4mCkCLoFfcwSfXLWbotd3M42lKnPBCyGdkVu5UQ1JaTkczUDlKTENYSFRYVlZNS1FIUU5BSy4u&route=shorturl">this  form</a> to register your interest in applying and get help creating a strong  application. </li>
