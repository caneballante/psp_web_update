        <h2 id="section3" class="resource-section-anchor">Sewer-related programs in Tacoma/Pierce County </h2>
        <p><strong>City of Tacoma Sewer Conservation Loan Program </strong></p>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.cityoftacoma.org/government/city_departments/environmentalservices/sewer_conservation_loan_program">Sewer Conservation  Loan Program - City of Tacoma</a></li>
          <li>Description: If your side sewer needs repair or replacement, you may be eligible for a low-interest sewer conservation loan.  To qualify for the loan, your home must be within the City of Tacoma city limits and be served by the Environmental Services Department. Check your utility bill if you are unsure whether your home meets this criteria. You must have good credit with Tacoma Public Utilities and a qualifying FICO score. </li>
        </ul>
        <p><strong>Pierce County Sewer Programs  and Financing</strong></p>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.piercecountywa.gov/7264/Sewer-Programs-and-Financing">Sewer Programs and  Financing | Pierce County, WA - Official Website</a></li>
          <li>Description: Contains information about  financial help for homeowners who have a sewer in need of repair/replacement as  well as help for homeowners and businesses who are required to connect to sewer  systems. </li>
        </ul>
        <p><strong>Depave Puget Sound</strong></p>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://piercecd.org/246/Depave-Puget-Sound">Depave Puget Sound | Pierce  Conservation District, WA</a></li>
          <li>Description:  A project to remove pavement in Pierce County. It aims to reduce water pollution and urban heat island effect by creating more green spaces. <a href="https://piercecd.org/246/Depave-Puget-Sound">Learn more</a>. </li>
          <li>Contact: Sarah Pyle; (253) 278-6493, <a href="mailto:Sarahp@piercecd.org">Sarahp@piercecd.org</a></li>
        </ul>
        <p><strong>City of Tacoma Low Impact Development surface water rate reduction</strong></p>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.tacomapermits.org/tip-sheet-index/low-impact-development">Low  Impact Development Surface Water Rate Reduction — Tacoma Permits</a></li>
          <li>Description: Property owners may qualify  for a surface water rate reduction if they choose to utilize permanent Low  Impact Development (LID) Best Management Practices (BMPs) beyond what is  required per the Stormwater Management Manual (SWMM) for development or  redevelopment or as a retrofit for stormwater management. <a href="https://www.12000raingardens.org/wp-content/uploads/2013/01/S-401-Low-Impact-Development-Surface-Water-Rate-Reduction.pdf">Read a tip sheet for  the program</a>.</li>
          <li>Contact: City  of Tacoma Environmental Services, Merita Trohimovich: (253) 502-2103		</li>
        </ul>
