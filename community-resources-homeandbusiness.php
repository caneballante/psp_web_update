        <h2 id="section2" class="resource-section-anchor">TACOMA</h2>
        <p><strong>Make a Splash Grant Program</strong></p>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.cityoftacoma.org/government/city_departments/environmentalservices/surface_water/make_a_splash_stormwater_project_funding#:~:text=Apply%20for%20a%20Make%20a%20Splash%20grant%20through,and%20restore%20our%20lakes%2C%20streams%20and%20Puget%20Sound.">Make  a Splash Stormwater Project Funding - City of Tacoma</a></li>
          <li>Description: The City of Tacoma’s Stormwater Management program awards projects with strong stormwater messaging as well as educational programs up to $4,000. The projects must be within Tacoma city limits and not about water conservation or clean drinking water. Awards can go to classroom projects, community projects, and business projects.</li>
          <li>Contact: Have questions?  Contact Nathaniel Wood, Make a Splash Grant Program Manager, at <a href="mailto:NWood@tacoma.gov">NWood@tacoma.gov</a> or call (253) 719-3771. </li>
        </ul>
        <p><strong>Tacoma Tree Foundation</strong></p>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://tacomatreefoundation.org/">Tacoma Tree Foundation</a></li>
          <li>Description: Serving both Greater Tacoma and Pierce County (Lakewood, Midland, Parkland, and South Hill), Tacoma Tree Foundation provides free trees, and planting assistance for designated programs. Free education events support community tree stewardship by providing access to tree care education and related resources. <a href="https://tacomatreefoundation.org/calendar">Find an event</a> and <a href="https://tacomatreefoundation.org/programs">read about planting projects, tree shares and related programs in Greater Tacoma.</a></li>
        </ul>
        <p><strong>Tacoma Public Utilities water rebates and resources</strong></p>
        <ul class="bullet-size-fix">
          <li>Website: <a href="https://www.mytpu.org/ways-to-save/business-rebates/#pattern_10">Business  Rebates - Tacoma Public Utilities</a></li>
          <li>Description: Businesses (including those who  rent their business space) can receive rebates for a variety of water-saving  equipment, such as dishwashers, steam cookers, and smart irrigation. They can  get a free water saving assessment. Learn more<a href="https://www.mytpu.org/ways-to-save/business-rebates/commercial-water-incentives/">here</a>. </li>
          <ul>
            <li>Homeowners can access the <a href="https://www.mytpu.org/ways-to-save/business-rebates/smart-irrigation-rebate-for-businesses/#pattern_10">smart  irrigation rebate,</a> <a href="https://www.mytpu.org/payment-billing/payment-information/payment-assistance/water-grants-and-loans/">financial  help replacing a leaking/aged water line</a>, and can get a <a href="https://www.mytpu.org/ways-to-save/save-water-lower-bill/">free water  saving kit</a> as well as tips on how to find and fix leaks to lower water  bills.</li>
            <li>Information about water supply and bottle  filling locations can be found<a href="https://www.mytpu.org/about-tpu/services/water/water-source/#pattern_6">here</a>. </li>
          </ul>
          <li><a href="https://www.mytpu.org/payment-billing/payment-information/payment-assistance/#pattern_1">Payment  Assistance - Tacoma Public Utilities</a></li>
          <ul class="bullet-size-fix">
            <li>Qualified homeowners can receive payment  assistance with utility bills. Available in Spanish. </li>
          </ul>
        </ul>
