        <h2 id="section3" class="resource-section-anchor">Sewer-related programs in Tacoma/Pierce County </h2>
        <h3>City of Tacoma Sewer Conservation Loan Program </h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.cityoftacoma.org/government/city_departments/environmentalservices/sewer_conservation_loan_program">Sewer Conservation  Loan Program - City of Tacoma</a></li>
          <li><strong>Description</strong>: If  your side sewer needs repair or replacement, you may be eligible for a  low-interest sewer conservation loan.  To  qualify for the loan, your home must be within the City of Tacoma city limits  and be served by the Environmental Services Department. Check your utility bill  if you are unsure whether your home meets this criteria. You must have good  credit with Tacoma Public Utilities and FICO score. </li>
        </ul>
        <h3>Pierce County Sewer Programs  and Financing</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.piercecountywa.gov/7264/Sewer-Programs-and-Financing">Sewer Programs and  Financing | Pierce County, WA - Official Website</a></li>
          <li><strong>Description</strong>: Contains information about  financial help for homeowners who have a sewer in need of repair/replacement as  well as help for homeowners and businesses who are required to connect to sewer  systems. </li>
        </ul>
        <h3>Depave Puget Sound</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://piercecd.org/246/Depave-Puget-Sound">Depave Puget Sound | Pierce  Conservation District, WA</a></li>
          <li><strong>Description</strong>: A project to remove pavement in  Pierce County. It aims to reduce water pollution and urban heat island effect  by creating more green spaces. Learn more<a href="https://piercecd.org/246/Depave-Puget-Sound">here</a>. </li>
          <li><strong>Contact</strong>: Melissa  Buckingham; (253) 845-9770, <a href="mailto:melissab@piercecd.org">melissab@piercecd.org</a></li>
        </ul>
        <h3>City of Tacoma Low Impact Development surface water rate reduction</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.tacomapermits.org/tip-sheet-index/low-impact-development">Low  Impact Development Surface Water Rate Reduction — Tacoma Permits</a></li>
          <li><strong>Description</strong>: Property owners may qualify  for a surface water rate reduction if they choose to utilize permanent Low  Impact Development (LID) Best Management Practices (BMPs) beyond what is  required per the Stormwater Management Manual (SWMM) for development or  redevelopment or as a retrofit for stormwater management. Tip sheet for  the program can be found<a href="https://www.12000raingardens.org/wp-content/uploads/2013/01/S-401-Low-Impact-Development-Surface-Water-Rate-Reduction.pdf">here</a>.</li>
          <li><strong>Contact</strong>: City  of Tacoma Environmental Services, Merita Trohimovich: (253) 502-2103</li>
        </ul>
        <h3>Watershed project small grant funding in Pierce County</h3>
        <ul class="bullet-size-fix">
          <li><strong>Website</strong>: <a href="https://www.piercecountywa.gov/1872/Small-Grants-Program">Watersheds  Small Grants Program | Pierce County, WA - Official Website</a></li>
          <li><strong>Description</strong>: The <a href="https://gcc02.safelinks.protection.outlook.com/?url=https%3A%2F%2Fwww.piercecountywa.gov%2F1872%2FSmall-Grants-Program&data=05%7C02%7Csigne.lindquist%40psp.wa.gov%7Cf930e1b5fdf04791661808dd7ec0f97c%7C11d0e217264e400a8ba057dcc127d72d%7C0%7C0%7C638806089487391983%7CUnknown%7CTWFpbGZsb3d8eyJFbXB0eU1hcGkiOnRydWUsIlYiOiIwLjAuMDAwMCIsIlAiOiJXaW4zMiIsIkFOIjoiTWFpbCIsIldUIjoyfQ%3D%3D%7C0%7C%7C%7C&sdata=Vhnr7Luv0pCI9c34SbXg9CvyqIoMmy7lcbx9IWdpfPc%3D&reserved=0">2025 Watersheds Small Grants Program</a> funds community projects that improve water quality, restore habitats, and  protect the environment. This grant is open to everyone! Nonprofits, schools,  teachers, tribes, local governments, and individuals are encouraged to apply  for up to <strong>$2,500</strong> to start neighborhood cleanups, build rain gardens,  remove invasive species, and more. Grant applications are due by <strong>April 30, 2025</strong>. </li>
        </ul>
