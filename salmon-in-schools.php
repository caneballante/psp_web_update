			<p>A new video features kids describing the <a href="https://wasalmonintheschools.org/" target="new">Salmon in the  Schools program,</a> an iconic environmental education opportunity for elementary  school students in Washington.</p>
        <p align="center"><img src="/images/salmoninschools1.png" width="547" height="348"></p>
            <p>What happens when a child helps a salmon grow up? We  followed third and fourth graders at 
              two Washington schools to find out.</p>
            <p>The Salmon in the Schools program brings salmon eggs to  classrooms, where students watch 
              them hatch, grow into tiny fry, and eventually make the  journey back to local streams. Along the way, they&rsquo;re learning about more than  the salmon life cycle. They&rsquo;re building a connection to a species that has  shaped the region and to the responsibility they&rsquo;ll one day inherit to care for  the lands and waters those salmon call home.</p>
            <p>From January through April 2026, the students allowed us in  on what they were learning. They told us about the role of salmon in the  ecosystem. They described the time they picked the winning fish during the  Mariners salmon run. They admitted that some (but not all) of their parents are  good at cooking salmon. They played salmon-themed games, wrote stories, and  decided that Fred was the best name for a fish.</p>
            <p>After spending time with these students, one thing became  clear: they are the best storytellers for the Salmon in the Schools program.  So, we handed them the microphone, squeezed ourselves into chairs built for  8-year-olds, and let them explain in their own words what it means to raise a  salmon.</p>
            <p>At a time when the future of programs like Salmon in the  Schools is uncertain, the students&rsquo; voices are a reminder of what&rsquo;s really at  stake. Today&rsquo;s classroom salmon become returning adults in a few years. And  today&rsquo;s curious kids become stewards of the rivers, forests, and communities  that depend on them. Raising these salmon is raising a generation that cares
              enough to help them recover.</p>
            <p>We hope you&rsquo;ll enjoy hearing their stories.</p>
