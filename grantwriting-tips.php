            <h2 id="section6">Logic Models and Evaluation             </h2>
            <h3>Logic Model</h3>
            <p>Are you unsure about some of  the objectives and outcomes for your project<strong>? </strong>Make a Logic Model! A  Logic Model is a visual exercise that can help your organization demonstrate  how the activities in your project will achieve results. Consider it as a flowchart,  of your project&rsquo;s inputs, activities, outputs, outcomes, and impacts. It should  be detailed, effective, and created collaboratively.  </p>
        <ul class="bullet-size-fix">
              <li><strong>Resources/inputs</strong>&nbsp;- all materials and personnel must complete a  project, such as volunteers, staff, or match. </li>
              <li><strong>Activities</strong>&nbsp;- the specific work of your project, such as  community meetings or riparian restoration. </li>
              <li><strong>Outputs</strong>&nbsp;- what will come directly from the activities  such as river miles restored?</li>
              <li><strong>Outcomes</strong>&nbsp;- the short-term change that you hope to see  through the activities of your project, such as improving water quality through  riparian restoration. </li>
              <li><strong>Impacts</strong>&nbsp;- the long-term change that you are hoping to  accomplish.</li>
              <ul>
                <li>&ldquo;A logic model is  a relatively simple image that reflects how and why a program will work. It  conceptualizes the resources needed, activities that will be initiated, outputs  (services or products delivered because of activities) and both short and long  term outcomes expected (evidence of change).&rdquo; – <a href="https://inside.ewu.edu/ogrd/proposal-preparation/writing-resources/logic-models/">Eastern Washington University</a></li>
              </ul>
            </ul>
            <p>Helpful Resources and  examples:</p>
        <ul class="bullet-size-fix">
              <li><a href="https://www.instrumentl.com/blog/how-to-build-logic-models-for-grants">How to Build a Logic Model for Grants | Instrumentl</a></li>
              <li><a href="https://inside.ewu.edu/ogrd/proposal-preparation/writing-resources/logic-models/">Logic Models – Office of Grant and Research  Development</a></li>
              <li><a href="https://ctb.ku.edu/en/table-of-contents/overview/models-for-community-health-and-development/logic-model-development/example">Chapter 2., Section 1. Developing a Logic Model or  Theory of Change - Examples | Community Tool Box</a></li>
              <li><a href="https://growingoutreach.nwf.org/resources/logic-models-key-elements/#:~:text=A%20logic%20model%20is%20a%20widely%20used%20planning,farmers,%20ranchers,%20and%20other%20stakeholders%E2%80%94with%20your%20conservation%20goals.">Logic Models: Key Elements - National Wildlife  Federation - Growing Outreach</a></li>
            </ul>
            <h3>Evaluation</h3>
            <p>Building  off the Logic Model, evaluation is a critical portion of your proposed grant  application. A funder wants to know how you will evaluate the program they will  be funding and how you are showing success. Clearly differentiating between  Outputs, Outcomes, and Impacts presents a clear picture to the funder. If you  are awarded and results and evaluation are not progressing as anticipated, do  not worry. Regular communication with your funder, honest reporting, and  pursing a holistic approach to determine where issues are arising from will  help you adapt and continue to implement your program. </p>
