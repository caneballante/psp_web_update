            <h2 id="section2">General Project Information</h2>
            <p>Create a fact sheet for your  potential project through answering the following questions:</p>
        <ul class="bullet-size-fix">
              <li><strong>Project Title:</strong> Create a concise project title. (Ideally with a 75-character  limit, including spaces)</li>
              <li><strong>Project  Sponsor:</strong> Who is the lead applicant  and receiving the grant funding (taking on fiscal responsibility and  management)? </li>
              <li><strong>Project  Partners:</strong> Aside from the project  sponsor, who will be responsible for project activities, or who will receive  some of the grant funding? </li>
              <li><strong>Site Location:</strong> Where is the project occurring? </li>
              <li><strong>Project Short  Description:</strong> Create a brief  description of the overall project and environmental benefits. (Ideally 500-character  limit, including spaces)</li>
              <li><strong>Project Long  Description:</strong> Enter a more detailed  description of the project&rsquo;s purpose, benefits, background information, and  other associated funding. (4,000-8,000 character limit, including spaces)</li>
              <li><strong>Overall Goal:</strong> Enter a short paragraph describing the overall goal  and environmental benefits. (1,000-character limit, including spaces)</li>
              <li><strong>Community  Planning:</strong> What community plans does  this project align with or help fulfill?</li>
              <li><strong>Total Cost:</strong> Enter the total project cost. This includes grant funding  and any other eligible or ineligible costs associated with the project.  Identify match amount if required/known. </li>
              <li><strong>Total Eligible  Cost:</strong> Enter the total amount of the  grant request. </li>
              <li><strong>Project  Duration:</strong> What is the timeframe for  completion?</li>
              <li><strong>What are the  project activities? Break each activity out with:</strong></li>
              <ul>
                <li>A short  description of the activity </li>
                <li>The outcome/goal  of the activity</li>
                <li>Estimated budget  amount </li>
                <li>Responsible  partners </li>
                <li>Identify any  deliverables and/or metrics </li>
              </ul>
              <li><strong>Decision  Points:</strong> Are there any sticking points  to the project? If so, what are they? Does land need to be acquired? Does there  need to be planning and community outreach before design work is started?  </li>
            </ul>
