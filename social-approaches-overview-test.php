	<p>We are all connected to Puget Sound through the many ways we  interact with our natural environment. Everyone has a role to play in Puget  Sound recovery efforts.<br>
Our many everyday actions and behaviors can have a harmful  impact on our health and the health of the Puget Sound. Fostering beneficial  activities and reducing damaging behaviors is a key step toward recovering  Puget Sound and maintaining a healthy environment that everyone enjoys.<br>
Social approaches are methods and actions that focus on  Puget Sound residents&rsquo; attitudes and behaviors affecting Puget Sound recovery.  These include education, outreach, public engagement, stewardship, social  marketing, technical assistance, and enforcement, among others.</p>
	<p>We support the use of social approaches  throughout the Action Agenda and Implementation Strategies. These approaches can  help build public and political support for many types of projects, and ensure  resiliency for future Puget Sound recovery efforts.</p>
	<h2>What are the differences between social sciences and social approaches?</h2>
    <p>Social science and social approaches are related, but they  are not the same.<br>
		<aside class="content-note content-note--float" aria-labelledby="social-approaches"><p>Social  approaches may be a community outreach program designed to encourage a  particular behavior. Social science can offer research and data to help decide  which types of community outreach methods work the best for a specific  community. Social science can also help us understand the behaviors and values  of these communities, which can better inform potential outreach, education, or  social marketing planning, implementation, and overall expectations. </p>
		 
		</aside>
      <h3>Social approaches </h3>
      <p>Social approaches are the methods and actions used to engage,  inform, and work with communities as part of ecosystem recovery efforts. These  can include social marketing, education, and outreach.</p>
  <h3>Social sciences </h3>
<p>Social science helps us understand people&rsquo;s  behaviors, values, and relationships with the environment. They can also help  us understand which social approaches are effective, the challenges they may  face, and how they can be improved.</p>
	<h2>Enabling Partners</h2>
			
<p>We primarily work with Puget Sound residents through our  network of local partners. These include Local Integrating Organizations  (LIOs), salmon recovery Lead Entities (LEs), Marine Resource Committees (MRCs),  and Education, Communication, and Outreach Networks (ECO Nets), among others. <br>
We support local partners who are practitioners of social  approaches and ensures they have the necessary resources to effectively engage  people in their local areas. <br>
Here are some of the ways we support and enable our  partners:</p>
<ul class="bullet-size-fix" type="disc">
  <li>We       support LIOs that coordinate planning and implementation of local       ecosystem recovery efforts.&nbsp;<a href="http://www.psp.wa.gov/LIO-overview.php">LEARN MORE</a>.</li>
  <li><em>Puget       Sound Starts Here</em>&nbsp;is a collaborative campaign that connects       individual Puget Sound residents to ways to help recover Puget Sound. We       are a member of the&nbsp;<em>Puget Sound Starts Here</em>&nbsp;steering       committee.&nbsp;<a href="http://www.pugetsoundstartshere.org/">LEARN MORE</a>.</li>
  <li>We maintain and periodically update resources to  assist partners who are implementing social approaches.&nbsp;<a href="https://pspwa.box.com/v/PartnerResources">LEARN MORE</a>.</li>
</ul>

<h2>History of Stewardship at the Partnership</h2>
			
  <p>From 2010 through September 2015, the U.S. Environmental  Protection Agency (EPA) provided $6 million in National Estuary Program funds  to the Puget Sound Partnership to support region wide programs in stewardship  and education. <br>
Our Stewardship and Outreach Program worked with hundreds of  local and regional partner organizations to increase awareness and  understanding, change harmful practices and behaviors, and strengthen social  and institutional infrastructure.&nbsp;<a href="https://pspwa.box.com/v/StewardshipFinalReport">LEARN MORE</a>.</p>
  <p>Although the EPA funding for the Stewardship and  Outreach Program has ended, the theories that formed the grant program continue  to guide our efforts in developing social approaches for inclusion in the  Action Agenda and local ecosystem recovery efforts.</p>
  <h2>PUBLIC OPINION SURVEYS </h2>
  <h3>SOUND BEHAVIOR INDEX</h3>
  <p>Surveys to measure behavior related to yard care, car  maintenance, home maintenance, pet/animal waste, onsite septic systems, small  farms, and recreational boating and fishing were conducted in 2012, 2013, and  2015. In addition, the first survey established the baseline and included a  segment asking about social capital, or the value of social connectedness. The  Sound Behavior Index is part of the&nbsp;<a href="http://www.psp.wa.gov/evaluating-vital-signs.php">Sound Stewardship Vital  Sign</a>&nbsp;and will continue to be monitored. <br>
    <a href="https://pspwa.box.com/s/45tqlfh4w6qidabkzlr21jy3y82xv0po">Read the Sound  Behavior Index reports</a>.</p>
  <h3>GENERAL PUBLIC OPINION SURVEY</h3>
  <p>The General Opinion Survey focused on people&rsquo;s general  knowledge, attitudes, beliefs, and sense of place related to Puget Sound.  Conducted in 2012, 2013, and 2015, the surveys helped identify characteristics  of the population useful for developing various stewardship activities. The  surveys informed the&nbsp;<a href="http://www.pugetsoundstartshere.org/" target="new">Puget Sound Starts Here</a>&nbsp;campaign and provided pilot data  related to the new Human Wellbeing Vital Sign indicators. <br>
    <a href="https://pspwa.box.com/s/uybht4wqvv0q04t6nltnsp9uyo9j6r3e">Read the Public  Opinion surveys</a>.</p>
  <h3>BARRIERS AND MOTIVATORS SURVEY</h3>
  <p>Three surveys concentrated on practices related to a healthy  Sound were carried out in 2012 to better understand barriers and motivators to  these practices. After the surveys, researchers conducted follow-up focus  groups to gain deeper perspectives into people&rsquo;s barriers to and motivations  for Sound-healthy practices.</p>
  <p><a href="https://pspwa.box.com/s/ja2gk1ewp6do4iqm1sfp8kqdtx8rv96d">Read the  Barriers and Motivators Surveys</a>.  </p>
